def sanitize_model_name(s: str) -> str:
    """Match lm_eval.utils.sanitize_model_name (for output_path subdir)."""
    return re.sub(r'["<>:/\\|?*\[\]]+', "__", s)


def _safe_run_tag_token(s: str) -> str:
    """Filesystem- and W&B–friendly token (no slashes or spaces)."""
    s = re.sub(r"[^a-zA-Z0-9_.-]+", "_", s.strip())
    s = re.sub(r"_+", "_", s).strip("_")
    return s or "x"


def _sampling_suffix(
    *,
    threshold: float,
    num_fewshot: int,
    batch_size: int,
    use_carry: bool,
    use_block_cache: bool,
    apply_chat_template: bool,
    bd_size: int,
    small_block_size: int,
    max_new_tokens: int,
    mask_id: int,
) -> str:
    t3 = f"{int(round(float(threshold) * 100)):03d}"
    parts = [f"t{t3}_fs{int(num_fewshot)}_bs{int(batch_size)}_c{'y' if use_carry else 'n'}"]
    if use_block_cache:
        parts.append("bc")
    if not apply_chat_template:
        parts.append("nochat")
    if bd_size != 32:
        parts.append(f"bd{bd_size}")
    if small_block_size != 8:
        parts.append(f"sb{small_block_size}")
    if max_new_tokens != 2048:
        parts.append(f"mnt{max_new_tokens}")
    if mask_id != 151665:
        parts.append(f"mid{mask_id}")
    return "__".join(parts)


def default_run_tag(
    *,
    task: str,
    resolved: str,
    is_hub: bool,
    threshold: float,
    num_fewshot: int,
    batch_size: int,
    use_carry: bool,
    use_block_cache: bool,
    apply_chat_template: bool,
    bd_size: int,
    small_block_size: int,
    max_new_tokens: int,
    mask_id: int,
    training_data: str = "",
) -> str:
    """Human-readable default run_tag: task, model identity, checkpoint step, sampling params."""
    task_s = _safe_run_tag_token(task.lower())
    samp = _sampling_suffix(
        threshold=threshold,
        num_fewshot=num_fewshot,
        batch_size=batch_size,
        use_carry=use_carry,
        use_block_cache=use_block_cache,
        apply_chat_template=apply_chat_template,
        bd_size=bd_size,
        small_block_size=small_block_size,
        max_new_tokens=max_new_tokens,
        mask_id=mask_id,
    )

    if is_hub:
        mid_raw = resolved.replace("/", "_")
        mid = _safe_run_tag_token(mid_raw)
        base = f"{task_s}__{mid}__{samp}"
    else:
        p = Path(resolved)
        name = p.name
        m = re.fullmatch(r"checkpoint-(\d+)", name)
        if m:
            model_run = _safe_run_tag_token(p.parent.name)
            ckpt = f"ck{m.group(1)}"
        else:
            model_run = _safe_run_tag_token(name)
            ckpt = "final"

        base = f"{task_s}__{model_run}__{ckpt}__{samp}"

    td = (training_data or "").strip()
    if td:
        base = f"{base}__td_{_safe_run_tag_token(td)}"
    return base


def checkpoint_label_and_step(model_path: Path) -> tuple[str, int | None]:
    label = model_path.name
    m = re.fullmatch(r"checkpoint-(\d+)", label)
    if m:
        return label, int(m.group(1))
    return label, None


def resolve_model_path(model_path: str, repo_root: Path) -> tuple[str, bool]:
    """Return (path string for model_args / lm_eval, is_hub_id).

    Mirrors train_scripts/eval_math500.sbatch case logic.
    """
    raw = model_path.strip()
    if not raw:
        raise SystemExit("model_path is empty")

    if raw.startswith("/"):
        p = Path(raw)
        if not (p / "config.json").is_file():
            raise SystemExit(
                f"MODEL_PATH '{raw}' is absolute but has no config.json."
            )
        return str(p.resolve()), False

    slash_count = raw.count("/")
    if slash_count >= 2:
        cand = (repo_root / raw).resolve()
        if (cand / "config.json").is_file():
            return str(cand), False
        parent = cand.parent
        msg = (
            f"MODEL_PATH '{raw}' has >=2 slashes (not a Hub id) but "
            f"{cand / 'config.json'} does not exist."
        )
        if parent.is_dir():
            sibs = sorted(parent.glob("*/"))
            if sibs:
                msg += "\nAvailable siblings:\n  " + "\n  ".join(
                    str(x) for x in sibs[:40]
                )
                if len(sibs) > 40:
                    msg += f"\n  ... ({len(sibs)} total)"
        raise SystemExit(msg)

    cand = (repo_root / raw).resolve()
    if (cand / "config.json").is_file():
        return str(cand), False
    return raw, True


def inject_vendored_modeling(local_dir: Path, repo_root: Path) -> None:
    """Copy vendored modeling.py / configuration.py into a local checkpoint dir."""
    if not local_dir.is_dir() or not (local_dir / "config.json").is_file():
        return
    vendored = repo_root / "src/lmflow/models/fast_dllm"
    for fname in ("modeling.py", "configuration.py"):
        src = vendored / fname
        dst = local_dir / fname
        if not src.is_file():
            raise SystemExit(f"Missing vendored file: {src}")
        if dst.is_file() and dst.read_bytes() == src.read_bytes():
            continue
        shutil.copy2(src, dst)
        print(f"Copied {src} -> {dst}", flush=True)


def expected_results_dir(output_dir: Path, model_path_str: str) -> Path:
    return output_dir / sanitize_model_name(model_path_str)


def _harness_get_model_stem_for_results_subdir(model_args: str) -> str | None:
    """Return the *unsanitized* model name that lm_eval uses for the subdir under output_path.

    Inlined from ``lm_eval.loggers.evaluation_tracker.GeneralConfigTracker._get_model_name``
    so ``submit_eval`` does not need ``import lm_eval`` (login nodes, dry runs). The harness
    can match a short ``path=`` *inside* ``model_path=...``, so the stem can differ from
    ``resolve_model_path`` (e.g. a leading ``=`` on the path segment).
    """

    def _extract_model_name(margs: str, key: str) -> str:
        args_after_key = margs.split(key, 1)[1]
        return args_after_key.split(",")[0]

    prefixes = ["peft", "delta", "pretrained", "model", "path", "engine"]
    if not isinstance(model_args, str):
        return None
    for prefix in prefixes:
        if f"{prefix}=" in model_args:
            return _extract_model_name(model_args, f"{prefix}=")
    return None


def _newest_json(paths: list[Path]) -> Path:
    try:
        return max(paths, key=lambda p: p.stat().st_mtime)
    except OSError:
        return sorted(paths)[-1]


def results_artifact_path(cfg: SubmitEvalConfig) -> Path | None:
    """``results_*.json`` in ``expected_results_path``, or under ``output_dir`` (legacy / mismatch)."""
    direct = list(cfg.expected_results_path.glob("results_*.json"))
    if direct:
        return _newest_json(direct) if len(direct) > 1 else direct[0]
    under = list(cfg.output_dir.rglob("results_*.json"))
    if not under:
        return None
    in_expected = [p for p in under if p.parent == cfg.expected_results_path]
    if in_expected:
        return _newest_json(in_expected) if len(in_expected) > 1 else in_expected[0]
    if len(under) == 1:
        return under[0]
    return _newest_json(under)


def results_already_present(expected_dir: Path) -> Path | None:
    """Check only the given directory (no rglob). Prefer :func:`results_artifact_path` with a full cfg."""
    matches = sorted(expected_dir.glob("results_*.json"))
    return matches[0] if matches else None


def git_head(repo_root: Path) -> str | None:
    try:
        out = subprocess.run(
            ["git", "-C", str(repo_root), "rev-parse", "HEAD"],
            check=True,
            capture_output=True,
            text=True,
        )
        return out.stdout.strip() or None
    except (OSError, subprocess.CalledProcessError):
        return None


_WANDB_TAG_MAX_CHARS = 64


def _tag_safe(s: str) -> str:
    out = re.sub(r"[^a-zA-Z0-9_\-]+", "_", s).strip("_")
    return (out or "x")[:_WANDB_TAG_MAX_CHARS]


