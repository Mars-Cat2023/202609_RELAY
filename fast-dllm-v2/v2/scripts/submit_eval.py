def build_wandb_init_dict(cfg: "SubmitEvalConfig") -> dict[str, Any]:
    tags: list[str] = ["eval", _tag_safe(cfg.task)]
    if cfg.model_root_basename:
        tags.append(_tag_safe(cfg.model_root_basename))
    tags.append("carry" if cfg.use_carry else "no_carry")
    if cfg.use_block_cache:
        tags.append("block_cache")
    if cfg.apply_chat_template:
        tags.append("chat_template")
    tags.append(_tag_safe(cfg.checkpoint_label))
    for t in cfg.wandb_tags_extra:
        tt = t.strip()
        if tt and tt not in tags:
            tags.append(_tag_safe(tt))

    d: dict[str, Any] = {
        "entity": cfg.wandb_entity,
        "project": cfg.wandb_project,
        "name": cfg.run_tag,
        "job_type": "eval",
        "tags": tags,
        "notes": "submitted by scripts/submit_eval.py",
    }
    if cfg.wandb_group:
        d["group"] = cfg.wandb_group
    return d


