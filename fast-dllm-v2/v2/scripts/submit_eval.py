def build_sbatch_text(cfg: "SubmitEvalConfig", accelerate_argv: list[str]) -> str:
    """Full sbatch script: header + repo guard + env + accelerate command."""
    out_log = shlex.quote(str(cfg.expected_results_path / "slurm-%j.out"))
    lines: list[str] = [
        SBATCH_HEADER.rstrip(),
        f"#SBATCH --output={out_log}",
        "",
        "set -euo pipefail",
        "",
    ]

    lines.append("# Paths")
    lines.append('if [ -n "${SLURM_SUBMIT_DIR:-}" ]; then')
    lines.append("    REPO_ROOT=${SLURM_SUBMIT_DIR}")
    lines.append("else")
    lines.append(f"    REPO_ROOT={shlex.quote(str(REPO_ROOT))}")
    lines.append("fi")
    lines.append(
        'if [ ! -f "${REPO_ROOT}/eval.py" ]; then'
        ' echo "ERROR: REPO_ROOT=${REPO_ROOT} missing eval.py" >&2; exit 1; fi'
    )
    lines.append('cd "${REPO_ROOT}"')
    lines.append(_env_block())

    if cfg.task in EVALPLUS_LM_EVAL_TASKS:
        lines.append(
            "# lm_eval_tasks imports + bundled harness (see lm_eval_tasks/README.md)"
        )
        lines.append(
            'export PYTHONPATH="${REPO_ROOT}/lib/lm-evalulation-harness:${REPO_ROOT}:${PYTHONPATH:-}"'
        )
        if cfg.evalplus_tokenizer.strip():
            lines.append(
                "export EVALPLUS_TOKENIZER="
                + shlex.quote(cfg.evalplus_tokenizer.strip())
            )

    lines.append('echo "===== JOB INFO ====="')
    lines.append('echo "SLURM_JOB_ID       = ${SLURM_JOB_ID:-<not in slurm>}"')
    lines.append('echo "SLURM_JOB_NODELIST = ${SLURM_JOB_NODELIST:-<not in slurm>}"')
    lines.append('echo "CUDA_VISIBLE_DEVICES = ${CUDA_VISIBLE_DEVICES:-}"')
    lines.append(f'echo "TASK               = {shlex.quote(cfg.task)}"')
    lines.append(f'echo "RUN_TAG            = {shlex.quote(cfg.run_tag)}"')
    lines.append(f'echo "OUTPUT_DIR         = {shlex.quote(str(cfg.output_dir))}"')
    lines.append(
        f'echo "EXPECTED_RESULTS   = {shlex.quote(str(cfg.expected_results_path))}"'
    )
    lines.append('echo "===================="')

    lines.append("_cmd=(")
    for a in accelerate_argv:
        lines.append(f"  {shlex.quote(a)}")
    lines.append(")")

    lines.append('echo "===== COMMAND (shell-quoted) ====="')
    lines.append('printf "%q " "${_cmd[@]}"')
    lines.append("echo")
    lines.append('echo "==================="')
    lines.append('"${_cmd[@]}"')
    lines.append("")

    return "\n".join(lines)


