def _lm_eval_arg_value(v: Any) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if v is None:
        return ""
    return str(v).replace(",", "_")


def _format_lm_eval_arg_string(d: dict[str, Any]) -> str:
    parts: list[str] = []
    for k, v in d.items():
        if isinstance(v, (list, tuple, dict, set)):
            continue
        parts.append(f"{k}={_lm_eval_arg_value(v)}")
    return ",".join(parts)


