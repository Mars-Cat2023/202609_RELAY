def build_accelerate_command(cfg: "SubmitEvalConfig", repo_root: Path) -> list[str]:
    model_args = build_model_args(cfg)
    cmd: list[str] = [
        "accelerate",
        "launch",
        "eval.py",
        "--tasks",
        cfg.task,
        "--batch_size",
        str(cfg.batch_size),
        "--num_fewshot",
        str(cfg.num_fewshot),
        "--confirm_run_unsafe_code",
        "--model",
        "fast_dllm_v2",
        "--output_path",
        str(cfg.output_dir),
        "--model_args",
        model_args,
        "--log_samples",
    ]
    if cfg.include_path_str:
        cmd.extend(["--include_path", str(repo_root / cfg.include_path_str)])
    if cfg.apply_chat_template:
        cmd.append("--apply_chat_template")
    if cfg.fewshot_as_multiturn:
        cmd.append("--fewshot_as_multiturn")

    if not cfg.no_wandb:
        init_d = build_wandb_init_dict(cfg)
        cfg_d = build_wandb_config_dict(cfg)
        cmd.extend(["--wandb_args", _format_lm_eval_arg_string(init_d)])
        cmd.extend(["--wandb_config_args", _format_lm_eval_arg_string(cfg_d)])

    return cmd


